-- 給与計算の運用開始日。この日より前の勤務は給与計算・締め・給与明細・税理士向けCSVの
-- 対象から外れる(勤務表・QR打刻の記録には影響しない)。設定画面から変更できる。
--
-- 背景: 給与期間は「前月26日〜当月25日」なので、2026年8月分は 7/26〜8/25 になる。
-- 2026/7/27 の開店から 7/31 までは日当を現金で手渡す運用のため、そのままだと 8/31 の
-- 給与にも同じ勤務が含まれて二重払いになる。開始日を 2026-08-01 にすることで
-- 2026年8月分は 8/1〜8/25 で計算され、7月中の勤務は日当レポート(/admin/daily)で精算する。
--
-- 空文字にすると制限なし(全期間が給与計算の対象)になる。
insert into public.app_settings (key, value)
values ('payroll_start_date', '2026-08-01')
on conflict (key) do nothing;
