/**
 * 一覧表の縞模様(ゼブラ)。行数の多い表で横に目が滑らないようにする(2026-09-11、オーナー依頼)。
 *
 * `tr:nth-child(even)` のようなCSSではなく引数で番号を渡す形にしているのは、
 * **給与明細画面のように1人が複数行(時給ごとの行分割)になる表がある**ため。
 * そこでは「行番号」ではなく「従業員の番号」を渡し、同じ人の行は同じ色にする。
 *
 * ⚠️ 横スクロールで固定している列(`sticky`)のセルは、背景色を直接指定せず
 * `bg-inherit` にすること。行(tr)の縞の色をそのまま引き継がせないと、
 * 固定列だけ白のまま浮いて見える。
 */
export function zebraRowClass(index: number): string {
  return index % 2 === 1 ? "bg-gray-50" : "bg-white";
}
